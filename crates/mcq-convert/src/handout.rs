//! The paper as a Markdown handout for students: no correct mark, no explanation, no rule, no
//! author note, options lettered A, B, C... in source order, to print or to read on screen.
//!
//! The handout is generated from the answer key and never edited by hand: fix the key, then
//! generate again. `mcq handout --check` tells when a handout no longer matches its key.

use std::fmt::Write as _;

use mcq_model::{Block, Paper, Question, Scoring};

struct Labels {
    generated: &'static str,
    questions: &'static str,
    single: &'static str,
    some_multiple: &'static str,
    partial: &'static str,
    duration: &'static str,
    unanswered: &'static str,
    wrong: &'static str,
    point: &'static str,
    points: &'static str,
    themes: &'static str,
    question: &'static str,
    several: &'static str,
    to_tick: &'static str,
    decimal: char,
}

const EN: Labels = Labels {
    generated: "<!-- Generated by `mcq handout` from the answer key. Do not edit by hand. -->",
    questions: "questions",
    single: "one correct answer per question.",
    some_multiple: "some questions have several correct answers.",
    partial: "Each correct box ticked earns part of the point.",
    duration: "Duration: {} min.",
    unanswered: "A question left blank costs {}.",
    wrong: "A wrong answer costs {}.",
    point: "point",
    points: "points",
    themes: "Themes:",
    question: "Question",
    several: "Several answers possible",
    to_tick: "to tick",
    decimal: '.',
};

const FR: Labels = Labels {
    generated: "<!-- Généré par `mcq handout` depuis le corrigé. Ne pas modifier à la main. -->",
    questions: "questions",
    single: "une seule bonne réponse par question.",
    some_multiple: "certaines questions ont plusieurs bonnes réponses.",
    partial: "Chaque bonne case cochée rapporte une part du point.",
    duration: "Durée : {} min.",
    unanswered: "Une question laissée sans réponse coûte {}.",
    wrong: "Une mauvaise réponse coûte {}.",
    point: "point",
    points: "points",
    themes: "Thèmes :",
    question: "Question",
    several: "Plusieurs réponses possibles",
    to_tick: "à cocher",
    decimal: ',',
};

const LETTERS: &str = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";

/// The handout of a paper, in the paper language (French or English), with LF line ends.
pub fn handout(paper: &Paper) -> String {
    let labels = if paper.lang.starts_with("fr") {
        &FR
    } else {
        &EN
    };
    let mut out = String::new();
    let _ = writeln!(out, "{}\n", labels.generated);
    let title = if paper.title.is_empty() {
        "MCQ"
    } else {
        &paper.title
    };
    let _ = writeln!(out, "# {title}\n");
    if !paper.description.is_empty() {
        let _ = writeln!(out, "{}\n", paper.description);
    }

    let ordered = in_theme_order(paper);
    let multiple = ordered.iter().any(|q| q.is_multiple());
    let mut rules = vec![format!(
        "{} {}, {}",
        ordered.len(),
        labels.questions,
        if multiple {
            labels.some_multiple
        } else {
            labels.single
        }
    )];
    if multiple && paper.scoring == Scoring::Partial {
        rules.push(labels.partial.to_string());
    }
    if paper.duration_minutes > 0 {
        rules.push(
            labels
                .duration
                .replace("{}", &paper.duration_minutes.to_string()),
        );
    }
    if paper.unanswered_penalty > 0.0 {
        rules.push(
            labels
                .unanswered
                .replace("{}", &points(paper.unanswered_penalty, labels)),
        );
    }
    if paper.penalty > 0.0 {
        rules.push(labels.wrong.replace("{}", &points(paper.penalty, labels)));
    }
    let _ = writeln!(out, "> {}", rules.join(" "));
    let themes: Vec<String> = paper
        .themes
        .iter()
        .map(|t| {
            let count = paper
                .questions
                .iter()
                .filter(|q| q.theme_id == t.id)
                .count();
            format!("{} ({count})", t.title)
        })
        .collect();
    if !themes.is_empty() {
        let _ = writeln!(out, ">\n> {} {}", labels.themes, themes.join(" · "));
    }

    let mut number = 0;
    let mut theme_id: Option<&str> = None;
    for question in ordered {
        if theme_id != Some(question.theme_id.as_str()) {
            theme_id = Some(question.theme_id.as_str());
            if let Some(theme) = paper.theme(&question.theme_id) {
                let _ = writeln!(out, "\n## {}", theme.title);
            }
        }
        number += 1;
        let _ = writeln!(out, "\n### {} {number}\n", labels.question);
        write_question(&mut out, question, paper.show_answer_count, labels);
    }
    out
}

/// Questions without a theme first, then each theme's questions: the order of the source.
fn in_theme_order(paper: &Paper) -> Vec<&Question> {
    let mut ordered: Vec<&Question> = paper
        .questions
        .iter()
        .filter(|q| paper.theme(&q.theme_id).is_none())
        .collect();
    for theme in &paper.themes {
        ordered.extend(paper.questions.iter().filter(|q| q.theme_id == theme.id));
    }
    ordered
}

fn points(value: f32, labels: &Labels) -> String {
    let unit = if value > 1.0 {
        labels.points
    } else {
        labels.point
    };
    let number = value.to_string().replace('.', &labels.decimal.to_string());
    format!("{number} {unit}")
}

fn write_question(out: &mut String, question: &Question, show_count: bool, labels: &Labels) {
    if question.is_multiple() {
        if show_count {
            let _ = writeln!(
                out,
                "*{} ({} {})*\n",
                labels.several,
                question.answers_to_tick(),
                labels.to_tick
            );
        } else {
            let _ = writeln!(out, "*{}*\n", labels.several);
        }
    }
    for block in &question.body {
        match block {
            Block::Text(text) => {
                let _ = writeln!(out, "{text}\n");
            }
            Block::Code(code) => {
                let _ = writeln!(out, "```{}\n{}\n```\n", code.language, code.source);
            }
            Block::Media(media) => {
                let _ = writeln!(out, "![{}]({})\n", media.alt, media.path);
            }
        }
    }
    for (option, letter) in question.options.iter().zip(LETTERS.chars()) {
        let _ = writeln!(out, "- **{letter}.** {}", option.text);
    }
}
